/**
 * Writes the registry URL and ingest secret into a generated module.
 *
 * Dev (default): reads .env then .env.local. Localhost is allowed.
 * Packaged (`--packaged`): reads .env.production only, never .env.local.
 * Packaging exits 1 when the URL is missing, local, or the secret is the dev placeholder.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { config as loadEnv } from 'dotenv';

const DEV_INGEST_SECRET = 'dev-only-ingest-secret';
const packaged = process.argv.includes('--packaged');

const __dirname = dirname(fileURLToPath(import.meta.url));
const desktopRoot = join(__dirname, '..');

if (packaged) {
  loadEnv({ path: join(desktopRoot, '.env.production') });
} else {
  loadEnv({ path: join(desktopRoot, '.env') });
  loadEnv({ path: join(desktopRoot, '.env.local'), override: true });
}

const url = process.env.REGISTRY_URL ?? '';
const secret = process.env.REGISTRY_INGEST_SECRET ?? '';

if (packaged) {
  const problem = packagedConfigError(url.trim(), secret.trim());
  if (problem) {
    console.error(`[inject-registry-config] Refusing to package: ${problem}`);
    console.error(
      '[inject-registry-config] Set REGISTRY_URL and REGISTRY_INGEST_SECRET in apps/desktop/.env.production (not .env.local).',
    );
    process.exit(1);
  }
}

const outPath = join(desktopRoot, 'src/registry/registry-config.generated.ts');
const contents = `// Generated by scripts/inject-registry-config.mjs — do not edit by hand.
// Ingest secret can only POST reports. Never bake the admin secret into this app.
export const REGISTRY_URL = ${JSON.stringify(url)};
export const REGISTRY_INGEST_SECRET = ${JSON.stringify(secret)};
`;

writeFileSync(outPath, contents, 'utf8');
console.log(
  packaged
    ? `[inject-registry-config] Wrote production REGISTRY_URL (${url.trim()}) and ingest secret length ${secret.trim().length}`
    : url
      ? `[inject-registry-config] Wrote dev REGISTRY_URL (${url}) and ingest secret length ${secret.length}`
      : '[inject-registry-config] Wrote empty REGISTRY_URL (reports stay off until set)',
);

function packagedConfigError(registryUrl, ingestSecret) {
  if (!registryUrl) return 'REGISTRY_URL is empty';
  if (!ingestSecret) return 'REGISTRY_INGEST_SECRET is empty';
  if (ingestSecret === DEV_INGEST_SECRET) return 'REGISTRY_INGEST_SECRET is still the dev placeholder';
  let host = '';
  try {
    host = new URL(registryUrl).hostname;
  } catch {
    return `REGISTRY_URL is not a valid URL (${registryUrl})`;
  }
  if (host === 'localhost' || host === '127.0.0.1' || host === '::1' || host.endsWith('.local')) {
    return `REGISTRY_URL points at a local host (${registryUrl})`;
  }
  return null;
}
